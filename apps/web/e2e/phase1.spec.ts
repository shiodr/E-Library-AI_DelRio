import { expect, test } from '@playwright/test'

test('landing, guest session, real catalog, and mobile navigation', async ({ page }, testInfo) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /your next chapter/i })).toBeVisible()
  await expect(page.locator('.landing-collection .book-card')).toHaveCount(4)
  await page.getByRole('button', { name: 'Continue as Guest' }).click()
  await expect(page.getByText('You’re exploring as a guest.')).toBeVisible()
  const navigation = page.getByRole('navigation', { name: testInfo.project.name === 'mobile' ? 'Mobile navigation' : 'Main navigation' })
  await navigation.getByRole('link', { name: /explore/i }).click()
  await expect(page.locator('.book-card')).toHaveCount(8)
  await page.getByRole('searchbox', { name: 'Search books' }).fill('Darwin')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.locator('.book-card')).toHaveCount(1)
  await page.locator('.book-card').click()
  await expect(page.getByRole('heading', { name: 'On the Origin of Species' })).toBeVisible()
  await expect(page.getByText(/Public domain in the USA/)).toBeVisible()
  await navigation.getByRole('link', { name: 'My Library' }).click()
  await expect(page.getByText('5-book download allowance planned')).toBeVisible()
  await navigation.getByRole('link', { name: /assistant/i }).click()
  await expect(page.getByText(/AI is not connected/)).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: /switch to dark mode/i }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'End guest session' }).click()
  await expect(page).toHaveURL('/')
})

test('web registration is usable through the Android API contract', async ({ page, playwright }) => {
  const email = `reader-${Date.now()}-${Math.random().toString(16).slice(2)}@example.com`
  const password = 'shared-backend-test-passphrase'
  await page.goto('/app/favorites')
  await expect(page).toHaveURL('/login')
  await page.getByRole('link', { name: 'Create an account' }).click()
  await page.getByLabel('Full name').fill('Student Reader')
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByLabel('Confirm password').fill(password)
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page).toHaveURL('/app/favorites')
  await expect(page.getByText('Student', { exact: true })).toBeAttached()
  const mobile = await playwright.request.newContext({ baseURL: 'http://127.0.0.1:8000/api/v1' })
  try {
    const login = await mobile.post('http://127.0.0.1:8000/api/v1/auth/login', { data: { email, password, client: 'android' } })
    expect(login.status()).toBe(200)
    const { access_token, user } = await login.json()
    expect(user.email).toBe(email)
    const headers = { Authorization: `Bearer ${access_token}` }
    const me = await mobile.get('http://127.0.0.1:8000/api/v1/auth/me', { headers })
    expect((await me.json()).user.id).toBe(user.id)
    expect((await mobile.post('http://127.0.0.1:8000/api/v1/auth/logout', { headers })).status()).toBe(204)
    expect((await mobile.get('http://127.0.0.1:8000/api/v1/auth/me', { headers })).status()).toBe(401)
  } finally { await mobile.dispose() }
  await page.getByRole('button', { name: 'Sign out' }).click()
  await page.goto('/login')
  await page.getByLabel('Email address').fill(email)
  await page.getByLabel('Password', { exact: true }).fill('wrong-password')
  await page.getByRole('button', { name: 'Log in' }).click()
  await expect(page.getByRole('alert')).toHaveText('Email or password is incorrect.')
  await page.getByLabel('Password', { exact: true }).fill(password)
  await page.getByRole('button', { name: 'Log in' }).click()
  await expect(page.getByRole('heading', { name: /Hello, Student\s*\./ })).toBeVisible()
})

